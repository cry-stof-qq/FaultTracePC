            + $"(from a base of {Analysis.DriverKnowledgeBase.Count} documented drivers), <strong>{family}</strong> matched to a known "
            + $"family, {thirdParty.Count - documented - family} undocumented. Hover the last column to see which software "
            + "a driver belongs to and what to do if it is involved in a crash.<br>"
            + "“(family)” marks an identification by platform: the advice holds but is generic, unlike a by-name "
            + "match, which gives the proven fix. A dash does not mean suspect — only undocumented.</p>"));
        sb.Append("</section>");
