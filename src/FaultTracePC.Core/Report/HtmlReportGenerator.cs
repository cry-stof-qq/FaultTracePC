    /// <summary>Processus en cours au moment du scan : RAM, CPU, débit disque.</summary>
    private static void ProcessesSection(StringBuilder sb, DiagnosticReport r)
    {
        sb.Append(Lang.T("<section class=\"tech\"><h2>Processus en cours au moment du scan</h2>", "<section class=\"tech\"><h2>Running processes at scan time</h2>"));
        sb.Append(Lang.T(
            "<p class=\"explain\">La liste des programmes qui tournaient pendant le scan, et ce qu'ils consommaient. "
            + "Utile pour repérer un programme qui monopolise la mémoire ou le processeur.</p>",
            "<p class=\"explain\">The list of programs that were running during the scan, and what they were using. "
            + "Useful for spotting a program that is hogging the memory or the processor.</p>"));
        if (r.Processes.Count == 0) { sb.Append(Lang.T("<p class=\"empty\">Relevé des processus indisponible.</p></section>", "<p class=\"empty\">Process readings unavailable.</p></section>")); return; }

        var os = r.System.Os;
        if (os.TotalVisibleMemoryKB > 0)
        {
            var physUsed = 100.0 * (os.TotalVisibleMemoryKB - os.FreePhysicalMemoryKB) / os.TotalVisibleMemoryKB;
            var commitUsed = os.TotalVirtualMemoryKB > 0
                ? 100.0 * (os.TotalVirtualMemoryKB - os.FreeVirtualMemoryKB) / os.TotalVirtualMemoryKB : 0;
            sb.Append(Lang.T($"<p class=\"sub2\">Mémoire physique utilisée : <strong>{physUsed:0} %</strong> ({RulesEngine.FormatBytes((os.TotalVisibleMemoryKB - os.FreePhysicalMemoryKB) * 1024)} / {RulesEngine.FormatBytes(os.TotalVisibleMemoryKB * 1024)})", $"<p class=\"sub2\">Physical memory in use: <strong>{physUsed:0}%</strong> ({RulesEngine.FormatBytes((os.TotalVisibleMemoryKB - os.FreePhysicalMemoryKB) * 1024)} / {RulesEngine.FormatBytes(os.TotalVisibleMemoryKB * 1024)})"));
            if (commitUsed > 0)
                sb.Append(Lang.T($" · Mémoire virtuelle engagée (RAM + fichier d'échange) : <strong>{commitUsed:0} %</strong>", $" · Virtual memory committed (RAM + page file): <strong>{commitUsed:0}%</strong>"));
