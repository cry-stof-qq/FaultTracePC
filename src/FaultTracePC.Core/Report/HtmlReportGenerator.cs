    /// <summary>
    /// État de santé affichable d'un disque. Quand rien n'a été rapporté, on retombe
    /// sur la valeur brute de WMI (« OK », « Degraded », « Pred Fail ») : c'est un mot
    /// de Windows, pas du nôtre — il n'est donc pas traduit. Seul le dernier recours
