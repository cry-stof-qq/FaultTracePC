    private static void Header(StringBuilder sb, DiagnosticReport r)
    {
        sb.Append("<header><div class=\"brand\">");
        sb.Append($"<img src=\"{Branding.LogoDataUri}\" alt=\"FaultTracePC\" width=\"48\" height=\"48\">");
        sb.Append(Lang.T("<h1>FaultTracePC — Rapport de diagnostic</h1></div>", "<h1>FaultTracePC — Diagnostic report</h1></div>"));
        sb.Append(Lang.T($"<p class=\"sub\">Machine <strong>{H(r.System.MachineName)}</strong> · {H(r.System.Os.Caption)} {H(r.System.Os.DisplayVersion)} (build {H(r.System.Os.BuildNumber)}) · généré le {r.GeneratedAt:dd/MM/yyyy à HH:mm} · période : {r.ScanPeriodDays} jours</p>", $"<p class=\"sub\">Machine <strong>{H(r.System.MachineName)}</strong> · {H(r.System.Os.Caption)} {H(r.System.Os.DisplayVersion)} (build {H(r.System.Os.BuildNumber)}) · generated on {r.GeneratedAt:yyyy-MM-dd HH:mm} · period: {r.ScanPeriodDays} days</p>"));
        // Fraîcheur : un rapport daté d'aujourd'hui laisse croire qu'il décrit
        // aujourd'hui. Sur une machine éteinte depuis des mois, il décrit un passé
        // lointain, et rien à la lecture ne permettait de s'en apercevoir.
        sb.Append("<p class=\"sub small\">")
          .Append(H(Analysis.DataFreshness.Sentence(Analysis.DataFreshness.Of(r), r.GeneratedAt)))
          .Append("</p>");
        sb.Append("<button id=\"mode-toggle\" class=\"btn2\" type=\"button\">").Append(H(BasculeVersComplet)).Append("</button>");
        sb.Append("</header>");
    }

    private static void VerdictBanner(StringBuilder sb, DiagnosticReport r)
    {
        var cls = r.Findings.Any(f => f.Severity == Severity.Critical) ? "crit"
                : r.Findings.Any(f => f.Severity == Severity.Warning) ? "warn" : "ok";
        sb.Append($"<div class=\"verdict {cls}\"><div class=\"verdict-label\">Verdict</div><div class=\"verdict-text\">{H(r.Verdict)}</div></div>");
    }

    /// <summary>
    /// « Et maintenant, je fais quoi ? »
    ///
    /// Un rapport de diagnostic laisse souvent son lecteur avec un constat et aucun
    /// point de départ. Ce bandeau indique qu'un assistant guidé existe dans le
    /// logiciel, juste sous le verdict — c'est-à-dire à l'endroit exact où la
    /// question se pose. Il n'apparaît que s'il y a réellement quelque chose à
    /// traiter : sur une machine saine, ce serait du bruit.
    /// </summary>
    private static void GuidedHint(StringBuilder sb, DiagnosticReport r)
    {
        bool somethingToDo = r.Findings.Any(f => f.Severity is Severity.Critical or Severity.Warning);
        if (!somethingToDo) return;

        var driver = r.Findings.FirstOrDefault(f =>
            f.Category == FaultCategory.Driver && f.Severity == Severity.Critical);

        sb.Append("<div class=\"guided\">");
        sb.Append(Lang.T("<div class=\"guided-t\">Tu ne sais pas par où commencer ?</div>", "<div class=\"guided-t\">Not sure where to start?</div>"));
        sb.Append(Lang.T(
            "<p>Dans FaultTracePC, le bouton <strong>« Je ne sais pas ce que j'ai »</strong> enchaîne tout seul "
            + "ce qu'il est possible de faire sans risque : point de restauration, examen, réparation des fichiers "
            + "système et de l'image Windows, contrôle du disque — puis il revérifie et conclut en une phrase. "
            + "Ce qui demande une décision t'est proposé à la fin, une action à la fois, avec sa raison.</p>",
            "<p>In FaultTracePC, the <strong>“I don't know what's wrong with it”</strong> button runs, on its own, "
            + "everything that can be done without risk: restore point, examination, repair of the system files "
            + "and of the Windows image, disk check — then it checks again and concludes in one sentence. "
            + "Anything needing a decision is offered at the end, one action at a time, with its reason.</p>"));

        if (driver is not null)
            sb.Append(Lang.T(
                "<p><strong>Dans ton cas</strong>, le problème principal vient d'un pilote. L'assistant ne le "
                + "remplacera pas à ta place — un pilote se choisit — mais il écarte tout le reste et te laisse "
                + "face à la seule action qui compte, décrite plus bas.</p>",
                "<p><strong>In your case</strong>, the main problem comes from a driver. The assistant will not "
                + "replace it for you — a driver is a choice — but it clears everything else out of the way and leaves "
                + "you facing the single action that matters, described below.</p>"));

        sb.Append("</div>");
    }

    /// <summary>Évolution depuis le scan précédent — la réponse à « est-ce que c'est réparé ? ».</summary>
    private static void ComparisonSection(StringBuilder sb, DiagnosticReport r)
    {
        var c = r.Comparison;
        if (c is null) return;

        sb.Append(Lang.T("<section><h2>Évolution depuis le dernier scan</h2>", "<section><h2>Change since the last scan</h2>"));
        sb.Append($"<div class=\"card {(c.Tone == "ok" ? "okcard" : c.Tone)}\">");
        sb.Append($"<h3>{H(c.Assessment)}</h3>");

        // Les dégradations matérielles se lisent AVANT le détail : ce sont elles qui
        // justifient la couleur de la carte, et les reléguer dans la liste du bas
        // reproduirait le défaut que ce bloc corrige.
        if (c.HardwareConcerns.Count > 0)
        {
            sb.Append("<ul class=\"concerns\">");
            foreach (var h in c.HardwareConcerns.OrderByDescending(x => x.Severity == "crit"))
                sb.Append($"<li class=\"{(h.Severity == "crit" ? "crit" : "warn")}\">{(h.Severity == "crit" ? "🛑" : "⚠️")} {H(h.Message)}</li>");
            sb.Append("</ul>");
        }

        var items = new List<string>();
        items.Add(c.NewBsodCount == 0
            ? Lang.T("✅ Aucun nouveau crash système", "✅ No new system crash")
            : Lang.T($"❌ {c.NewBsodCount} nouveau(x) crash(s) : {H(string.Join(" · ", c.NewBsods))}", $"❌ {c.NewBsodCount} new crash(es): {H(string.Join(" · ", c.NewBsods))}"));
        if (c.NewWheaEvents > 0) items.Add(Lang.T($"⚠️ {c.NewWheaEvents} nouvelle(s) erreur(s) matérielle(s) WHEA", $"⚠️ {c.NewWheaEvents} new WHEA hardware error(s)"));
        if (c.NewDiskErrorEvents > 0) items.Add(Lang.T($"⚠️ {c.NewDiskErrorEvents} nouvelle(s) erreur(s) disque", $"⚠️ {c.NewDiskErrorEvents} new disk error(s)"));
        if (c.DriverUpdates.Count > 0) items.Add(Lang.T($"🔄 Pilotes mis à jour : {H(string.Join(" · ", c.DriverUpdates))}", $"🔄 Drivers updated: {H(string.Join(" · ", c.DriverUpdates))}"));
        if (c.DiskChanges.Count > 0) items.Add(Lang.T($"💽 Disques : {H(string.Join(" · ", c.DiskChanges))}", $"💽 Drives: {H(string.Join(" · ", c.DiskChanges))}"));
        if (!string.IsNullOrEmpty(c.MemoryTrend)) items.Add($"🧠 {H(c.MemoryTrend)}");

        sb.Append("<p>").Append(string.Join("<br>", items)).Append("</p>");
        sb.Append("</div></section>");
    }

    private static void Findings(StringBuilder sb, DiagnosticReport r)
    {
        sb.Append(Lang.T("<section><h2>Conclusions du diagnostic</h2>", "<section><h2>Diagnostic findings</h2>"));
        sb.Append(Lang.T(
            "<p class=\"explain\">Ce que FaultTracePC a trouvé, classé du plus grave au moins grave. Chaque carte explique le problème en clair et dit quoi faire. "
            + "Le niveau de confiance est honnête : « faible » signale une piste à vérifier, pas une certitude.</p>",
            "<p class=\"explain\">What FaultTracePC found, ordered from most to least serious. Each card explains the problem in plain words and says what to do. "
            + "The confidence level is honest: “low” marks a lead to check, not a certainty.</p>"));
        // Tout le critique reste visible ; le reste se replie quand il y en a assez
        // pour que cacher aide plus que gêner. Voir Analysis.FindingDisplay.
        var split = Analysis.FindingDisplay.Split(r.Findings);
        foreach (var f in split.Visibles) FindingCard(sb, f);

        if (split.Repliees.Count > 0)
        {
            sb.Append("<details class=\"fold\"><summary>")
              .Append(H(Analysis.FindingDisplay.FoldLabel(split.Repliees)))
              .Append("</summary>");
            foreach (var f in split.Repliees) FindingCard(sb, f);
            sb.Append("</details>");
        }
        sb.Append("</section>");
    }

    /// <summary>
    /// Une carte de conclusion. Extraite de la boucle parce qu'elle est rendue à
    /// deux endroits désormais : dans la liste visible et dans le bloc replié.
    /// </summary>
    private static void FindingCard(StringBuilder sb, Finding f)
    {
            var (cls, label) = f.Severity switch
            {
                Severity.Critical => ("crit", Lang.T("Critique", "Critical")),
                Severity.Warning => ("warn", Lang.T("Avertissement", "Warning")),
                _ => ("info", Lang.T("Information", "Information")),
            };
            var conf = f.Confidence switch
            {
                Confidence.High => Lang.T("confiance élevée", "high confidence"),
                Confidence.Medium => Lang.T("confiance moyenne", "medium confidence"),
                _ => Lang.T("confiance faible", "low confidence"),
            };
            sb.Append($"<div class=\"card {cls}\"><div class=\"card-head\"><span class=\"badge {cls}\">{label}</span>");
            sb.Append($"<span class=\"conf\">{CategoryLabel(f.Category)} · {conf}</span></div>");
            sb.Append($"<h3>{H(f.Title)}</h3><p>{H(f.Details)}</p>");
            if (!string.IsNullOrEmpty(f.Recommendation))
                // « Recommandation » et « Recommendation » ne diffèrent que d'une
                // lettre : aucun des trois signaux du test de traduction ne pouvait
                // voir cette fuite — ni accent, ni trois mots outils, ni espace avant
                // une ponctuation. Elle a vécu dans le rapport anglais jusqu'en 1.4.
                sb.Append("<p class=\"reco\"><span class=\"recolabel\">")
                  .Append(Lang.T("💡 Recommandation", "💡 Recommendation"))
                  .Append($"</span> {H(f.Recommendation)}</p>");

            // Le rapport conseillait des actions sans jamais dire qu'un bouton les
            // exécute : le mot « Outils » n'apparaissait nulle part. Un lecteur qui
            // ne connaît pas déjà le logiciel n'avait aucun moyen de faire le lien.
            if (ToolboxHint(f.Category) is { } hint)
                sb.Append(Lang.T($"<p class=\"toolhint\"><span class=\"toollabel\">🧰 Dans FaultTracePC</span> bouton <strong>🧰 Outils</strong>, puis : {H(hint)}</p>", $"<p class=\"toolhint\"><span class=\"toollabel\">🧰 In FaultTracePC</span> button <strong>🧰 Tools</strong>, then: {H(hint)}</p>"));
            sb.Append("</div>");
    }

