using System.Text;
using FaultTracePC.Core.Analysis;

namespace FaultTracePC.Core.Report;

/// <summary>
/// Génère le rapport de diagnostic HTML autonome (aucune ressource externe),
/// en français, lisible par un non-spécialiste mais complet pour un technicien.
/// </summary>
public static class HtmlReportGenerator
{
    /// <summary>
    /// Nom de fichier d'un rapport — UNE seule formule pour les trois écrivains :
    /// application, ligne de commande et service.
    ///
    /// LE DÉFAUT QU'ELLE SUPPRIME, constaté le 30/08/2026 sur un rapport réel :
    /// la ligne de commande écrivait « Diagnostic_TECH-INFO-2025_… » et
    /// l'application « Diagnostic_PC_… », un reliquat d'avant que le nom de
    /// machine existe. Deux familles de noms pour la même chose dans le même
    /// dossier — et, sur un partage où plusieurs postes déposent leurs rapports,
    /// deux machines analysant à la même minute s'écrasaient l'une l'autre.
    /// </summary>
    public static string NomDuRapport(DiagnosticReport r) =>
        $"Diagnostic_{NomDeMachineSur(r.System?.MachineName)}_{r.GeneratedAt:yyyy-MM-dd_HHmm}.html";

    /// <summary>
    /// Nom de machine réduit à ce que <see cref="EstUnNomDeRapport"/> accepte :
    /// lettres, chiffres, tiret et tiret bas. Tout le reste devient un tiret bas.
    /// L'invariant compte plus que l'esthétique : un nom que nous produisons doit
    /// toujours passer notre propre contrôle, sinon la console ne pourrait plus
    /// télécharger le rapport d'une machine au nom exotique.
    /// </summary>
    public static string NomDeMachineSur(string? machineName)
    {
        var brut = string.IsNullOrWhiteSpace(machineName) ? Environment.MachineName : machineName.Trim();
        var propre = string.Concat(brut.Select(c => char.IsLetterOrDigit(c) || c is '-' or '_' ? c : '_'));
        return propre.Length == 0 ? "PC" : propre;
    }

    /// <summary>
    /// Contrôle du nom réclamé par la console avant de servir un fichier.
    ///
    /// C'est d'abord un garde-fou de sécurité : il n'accepte ni point, ni
    /// séparateur de chemin, ni deux-points, donc aucune traversée de répertoire.
    /// Il accepte les DEUX formes, l'ancienne « Diagnostic_PC_… » et la nouvelle
    /// qui porte le nom de machine — sans quoi les rapports déjà déposés dans le
    /// dossier partagé deviendraient invisibles du jour au lendemain.
    /// </summary>
    public static bool EstUnNomDeRapport(string? nom) =>
        nom is not null && NomDeRapportRx.IsMatch(nom);

    private static readonly System.Text.RegularExpressions.Regex NomDeRapportRx =
        new(@"^Diagnostic_[\w\-]+\.html$", System.Text.RegularExpressions.RegexOptions.Compiled);

    public static string Generate(DiagnosticReport r)
    {
        var sb = new StringBuilder(64 * 1024);
        sb.Append("<!DOCTYPE html><html lang=\"fr\"><head><meta charset=\"utf-8\">");
        sb.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">");
        sb.Append(Lang.T($"<title>Diagnostic {H(r.System.MachineName)} — {r.GeneratedAt:dd/MM/yyyy}</title>",
                         $"<title>Diagnosis {H(r.System.MachineName)} — {r.GeneratedAt:yyyy-MM-dd}</title>"));
        // Mode simple par défaut : l'essentiel d'abord, les détails techniques sur demande.
        sb.Append("<style>").Append(Css).Append("</style></head><body class=\"simple\">");

        Header(sb, r);
        VerdictBanner(sb, r);
        GuidedHint(sb, r);
        ComparisonSection(sb, r);
        Findings(sb, r);
        RepairSection(sb, r);
        FlightSection(sb, r);
        BsodSection(sb, r);
        DumpSection(sb, r);
        ProcessesSection(sb, r);
        EventsSection(sb, r);
        SystemSection(sb, r);
        SmartSection(sb, r);
        DriversSection(sb, r);
        ReliabilitySection(sb, r);
        ErrorsSection(sb, r);

        sb.Append(Lang.T($"<footer>Généré par <strong>FaultTracePC</strong> v{UpdateChecker.CurrentVersion} le {r.GeneratedAt:dd/MM/yyyy à HH:mm} — période analysée : {r.ScanPeriodDays} jours. ", $"<footer>Generated by <strong>FaultTracePC</strong> v{UpdateChecker.CurrentVersion} on {r.GeneratedAt:yyyy-MM-dd HH:mm} — period analysed: {r.ScanPeriodDays} days. "));
        sb.Append(Lang.T("Les niveaux de confiance sont indiqués honnêtement : une confiance « faible » signale une piste, pas une preuve.</footer>", "Confidence levels are stated honestly: “low” confidence marks a lead, not a proof.</footer>"));
        sb.Append("<script>const FTPC_L={complet:").Append(Js(BasculeVersComplet))
          .Append(",simple:").Append(Js(BasculeVersSimple)).Append("};")
          .Append(FilterJs).Append("</script>");
        sb.Append("</body></html>");
        return sb.ToString();
    }

    /// <summary>
    /// Écrit le rapport (et le script de réparation s'il y a des problèmes)
    /// dans Documents\FaultTracePC et retourne le chemin du rapport HTML.
    /// </summary>
    public static string WriteToDisk(DiagnosticReport r)
    {
        // Le script d'abord : le rapport HTML référence son chemin et embarque son contenu.
        RepairScriptGenerator.WriteToDisk(r); // renseigne RepairScriptPath + RepairLauncherPath

        var dir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments), "FaultTracePC");
        Directory.CreateDirectory(dir);
        var path = Path.Combine(dir, NomDuRapport(r));
        File.WriteAllText(path, Generate(r), Encoding.UTF8);

        // Copie vers le dossier partagé (servi par l'API du mode Client) — best effort.
        try
        {
            Directory.CreateDirectory(RemoteConfig.SharedReportsDir);
            File.Copy(path, Path.Combine(RemoteConfig.SharedReportsDir, Path.GetFileName(path)), overwrite: true);
        }
        catch { /* partage indisponible : le rapport local reste la référence */ }

        return path;
    }

